const LanguageContext = createContext();

/**
 * Idioma inicial: el que el usuario eligió antes (localStorage); si no eligió ninguno,
 * inglés cuando el navegador está en inglés y español (idioma base) en cualquier otro caso.
 */
const detectarIdiomaInicial = () => {
  const guardado = localStorage.getItem('upad_web_language');
  if (guardado && TRANSLATIONS[guardado]) return guardado;
  const navegador = (typeof navigator !== 'undefined' && navigator.language) || '';
  return navegador.toLowerCase().startsWith('en') ? 'en' : 'es';
};

export const LanguageProvider = ({ children }) => {
  const [language, setLanguage] = useState(detectarIdiomaInicial);

  const changeLanguage = (newLang) => {
    if (TRANSLATIONS[newLang]) {
      setLanguage(newLang);
      localStorage.setItem('upad_web_language', newLang);
      document.documentElement.lang = newLang;
    }
  };

  useEffect(() => {
    document.documentElement.lang = language;
  }, [language]);

  /**
   * Traduce una clave. Con `vars`, reemplaza los marcadores {nombre} del texto (p. ej. t(clave, { total: 3 })).
   */
  const t = (key, vars) => {
    const texto = TRANSLATIONS[language]?.[key] || TRANSLATIONS['es']?.[key] || TRANSLATIONS['en']?.[key] || key;
    if (!vars) return texto;
    return texto.replace(/\{(\w+)\}/g, (marca, nombre) => (vars[nombre] !== undefined && vars[nombre] !== null ? String(vars[nombre]) : marca));
  };

  /** Código de idioma para fechas y números (Intl / toLocaleString) según el idioma activo. */
  const locale = language === 'en' ? 'en-US' : language === 'es' ? 'es-PE' : language;

  /**
   * Traduce texto dinámico (como títulos de rutinas, pasos o palabras clave de la base de datos).
   * Si no está en el mapa, devuelve el texto original intacto.
   */
  const translateDynamicText = (text) => {
    if (!text || typeof text !== 'string') return text;
    const clean = text.trim().toLowerCase();
    const vocab = VOCABULARY_TRANSLATIONS[language] || {};
    return vocab[clean] || text;
  };

  return (
    <LanguageContext.Provider
      value={{
        language,
        locale,
        changeLanguage,
        t,
        translateDynamicText,
        supportedLanguages: SUPPORTED_LANGUAGES,
      }}
    >
      {children}
    </LanguageContext.Provider>
  );
};

export const useLanguage = () => {
  const context = useContext(LanguageContext);
  if (!context) {
    throw new Error('useLanguage debe ser utilizado dentro de un LanguageProvider');
  }
  return context;
};
